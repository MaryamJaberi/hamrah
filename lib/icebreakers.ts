function shuffle<T>(a: T[], seed: number) {
  const x = [...a];
  let s = seed || 1;
  for (let i = x.length - 1; i > 0; i--) { s = (s * 9301 + 49297) % 233280; const j = Math.floor((s / 233280) * (i + 1)); [x[i], x[j]] = [x[j], x[i]]; }
  return x;
}

/** Pick starters that fit the group's shared hobbies and planned activity. */
export function pickIcebreakers(opts: { hobbies?: string[]; activity?: string; expat?: boolean; seed?: number; n?: number }): Ice[] {
  const seed = opts.seed ?? Date.now() % 10000;
  const out: Ice[] = [];
  for (const h of opts.hobbies ?? []) for (const q of BY_HOBBY[h] ?? []) out.push({ kind: 'سؤال', text: q, tag: h });
  for (const q of BY_ACTIVITY[opts.activity ?? ''] ?? []) out.push({ kind: 'سؤال', text: q, tag: opts.activity });
  const pool: Ice[] = [
    ...shuffle(LIGHT, seed).slice(0, 4).map((t) => ({ kind: 'سؤال' as const, text: t, tag: 'سبک' })),
    ...(opts.expat !== false ? shuffle(EXPAT, seed + 1).slice(0, 2).map((t) => ({ kind: 'سؤال' as const, text: t, tag: 'زندگی در هلند' })) : []),
    ...shuffle(DEEP, seed + 2).slice(0, 2).map((t) => ({ kind: 'سؤال' as const, text: t, tag: 'عمیق‌تر' })),
    ...shuffle(GAMES, seed + 3).slice(0, 3),
  ];
  return [...shuffle(out, seed).slice(0, 4), ...pool].slice(0, opts.n ?? 10);
}
